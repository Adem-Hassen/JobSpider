def fold(text: str) -> str:
    """Lowercase, strip accents and collapse whitespace."""
    decomposed = unicodedata.normalize("NFKD", text)
    stripped = "".join(c for c in decomposed if not unicodedata.combining(c))
    return re.sub(r"\s+", " ", stripped).strip().lower()


_BY_NAME: dict[str, str] = {fold(name): code for code, name in ISO_NAMES.items()}
_BY_NAME.update({fold(alias): code for alias, code in _ALIASES.items()})


def country_code(text: str) -> str | None:
    """ISO alpha-2 code for a country name, alias or code; None if not a country."""
    value = text.strip().strip(".()")
    if len(value) == 2 and value.isalpha() and value.isupper():
        upper = value.upper()
        if upper == "UK":
            return "GB"
        return upper if upper in ISO_NAMES else None
    return _BY_NAME.get(fold(value))


def city_country(city: str) -> str | None:
    return CITY_COUNTRY.get(fold(city))


def is_region(text: str) -> bool:
    return fold(text).strip(" .()") in REGIONS
